"""Turns a picture on a baked-in checkerboard (no alpha) into a transparent image for the overlay, as a C++ header of
0xAARRGGBB pixels. The checkerboard is cleared by a flood fill from the edges over grey pixels; the icons' dark outlines
and coloured glow stop it. Usage: python tools/make_overlay_image.py <image> <height px> <C++ name> <header out>"""
import sys
from collections import deque
from PIL import Image, ImageFilter

src, height, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
im = Image.open(src).convert('RGB')
W, H = im.size
px = im.load()

def background_like(p):
    r, g, b = p
    return max(r, g, b) - min(r, g, b) <= 22 and 95 <= (r + g + b) // 3 <= 240

alpha = Image.new('L', (W, H), 255)
a = alpha.load()
seen = bytearray(W * H)
q = deque()
for x in range(W):
    q.append((x, 0)); q.append((x, H - 1))
for y in range(H):
    q.append((0, y)); q.append((W - 1, y))
while q:
    x, y = q.popleft()
    i = y * W + x
    if seen[i]:
        continue
    seen[i] = 1
    if not background_like(px[x, y]):
        continue
    a[x, y] = 0
    if x > 0: q.append((x - 1, y))
    if x < W - 1: q.append((x + 1, y))
    if y > 0: q.append((x, y - 1))
    if y < H - 1: q.append((x, y + 1))

# Eat the checker's last pixel around the edge, and soften it.
alpha = alpha.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(1.2))
rgba = im.copy()
rgba.putalpha(alpha)
box = alpha.point(lambda v: 255 if v > 40 else 0).getbbox()
rgba = rgba.crop(box)
w = round(rgba.width * height / rgba.height)
small = rgba.resize((w, height), Image.LANCZOS)
small.save(out.rsplit('.', 1)[0] + '_preview.png')

pix = small.load()
vals = []
for y in range(height):
    for x in range(w):
        r, g, b, al = pix[x, y]
        vals.append(f'0x{al:02X}{r:02X}{g:02X}{b:02X}')
with open(out, 'w', newline='\n') as f:
    f.write('#pragma once\n// Generated by tools/make_overlay_image.py from ' + src.replace('\\', '/').split('/')[-1] + ' -- do not edit.\n')
    f.write('#include <cstdint>\n\nnamespace vrmod {\n\n')
    f.write(f'constexpr int {name}W = {w}, {name}H = {height};\n')
    f.write(f'constexpr uint32_t {name}[{w * height}] = {{   // 0xAARRGGBB, not premultiplied\n')
    for k in range(0, len(vals), 12):
        f.write('    ' + ', '.join(vals[k:k + 12]) + ',\n')
    f.write('};\n\n}\n')
print(f'{w}x{height}, cropped from {box}')
